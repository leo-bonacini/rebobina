export const STRINGS = { en, pt, es };

export function initialLanguage(saved) {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  for (const candidate of [fromUrl, saved, ...(navigator.languages || [navigator.language])]) {
    const code = String(candidate || "").slice(0, 2).toLowerCase();
    if (code in STRINGS) return code;
  }
  return "en";
}
